import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {readFile,writeFile} from 'node:fs/promises';
const require=createRequire(new URL('../../app/package.json',import.meta.url));
const {build}=require('esbuild');
const output=new URL('./worker-bundle.mjs',import.meta.url);
const result=await build({absWorkingDir:fileURLToPath(new URL('../../',import.meta.url)),entryPoints:['server/garmin-ingress/worker.mjs'],bundle:true,write:false,format:'esm',platform:'browser',target:'es2022',banner:{js:'// Generated by server/garmin-ingress/build-worker.mjs; do not edit.'}});
const source=result.outputFiles[0].text;
if(process.argv.includes('--check')){if((await readFile(output,'utf8')).replaceAll('\r\n','\n')!==source.replaceAll('\r\n','\n'))throw new Error('Garmin ingress Worker bundle is stale.');}
else await writeFile(output,source);
console.log(JSON.stringify({check:process.argv.includes('--check'),bytes:Buffer.byteLength(source)}));
