  function answerOptions(q, mode, chatScenes) {
    if (chatScenes && q.chat) return q.chat.replies;
    return mode === 'imagine' && q.imagineOptions ? q.imagineOptions : q.options;
  }

  function score(packId, answers, mode = 'experience', chatScenes = false) {
    const pack = packs[packId];
    if (!Object.hasOwn(packs, packId)) throw new RangeError('알 수 없는 런비티아이 검사입니다.');
    const isImagination = mode === 'imagine';
    const counts = pack.domains.map(() => [0, 0, 0]);
    const selections = [];
    pack.questions.forEach((question, q) => {
      const input = Array.isArray(answers?.[q]) ? answers[q] : [];
      const choices = [...new Set(input.filter(i => Number.isInteger(i) && i >= 0 && i < 3))].slice(0, 2);
      const options = answerOptions(question, mode, chatScenes);
      for (const i of choices) {
        counts[question.domain][i]++;
        selections.push({ q, i, domain: question.domain, text: options[i] });
      }
    });
    const leaders = counts.map(row => {
      const max = Math.max(...row);
      return max === 0 ? [] : row.map((count, i) => count === max ? i : -1).filter(i => i >= 0);
    });
    const digest = leaders.map(indices => indices.length === 1 ? indices[0] : null);
    const unknown = leaders.every(indices => indices.length === 0);
    const itemsAnswered = pack.domains.map((_, domain) =>
      new Set(selections.filter(s => s.domain === domain).map(s => s.q)).size);
    // Two picks on a single screen describe that scene. A mixed result needs separate scenes.
    const tieDomain = leaders.reduce((best, indices, domain) => {
      if (indices.length < 2 || itemsAnswered[domain] < 2) return best;
      return best < 0 || itemsAnswered[domain] > itemsAnswered[best] ? domain : best;
    }, -1);
    const repeated = counts.map(row => Math.max(...row) >= 2);
    const kind = unknown ? 'open' : tieDomain >= 0 ? 'mixed' : repeated.every(Boolean) ? 'clear' : 'scene';

    // Keep legacy character indices stable for saved results and existing share cards.
    const anchor = leaders.map((indices, domain) => {
      const choice = selections.find(s => s.domain === domain && indices.includes(s.i));
      return choice?.i ?? 0;
    });
    const localIndex = packId === 'base' ? 9 * anchor[0] + 3 * anchor[1] + anchor[2] : 3 * anchor[0] + anchor[1];
    const characterIndex = localIndex + ({ base: 0, buddy: 27, record: 36 })[packId];
    const cast = ({ base: baseCast, buddy: buddyCast, record: recordCast })[packId];
    let [name, line] = cast[localIndex];
    if (isImagination) line = imaginedLines[packId][localIndex];
    if (kind === 'clear' && extensionEndings[packId]) line += ' ' + extensionEndings[packId][anchor[2]];

    // Keep one actual response for each leading choice, including ties.
    const evidence = [];
    for (const [domain, indices] of leaders.entries()) {
      for (const i of indices) {
        const choice = selections.find(s => s.domain === domain && s.i === i);
        if (choice) evidence.push({ q: choice.q, i: choice.i, text: choice.text });
      }
    }
    let focusDomain = null;
    if (kind === 'open') {
      name = '내가 고르는 첫 장면';
      line = '오늘은 마음에 드는 장면부터 골라 볼래.';
    } else if (kind === 'mixed') {
      const indices = leaders[tieDomain];
      focusDomain = tieDomain;
      const tieKey = ['01', '02', '12', '012'].indexOf(indices.join(''));
      const card = mixedCards[packId][tieDomain][tieKey];
      name = card[0];
      line = card[isImagination ? 2 : 1];
    } else if (kind === 'scene') {
      focusDomain = counts.map(row => Math.max(...row)).indexOf(Math.max(...counts.flat()));
      const picked = evidence.filter(e => pack.questions[e.q].domain === focusDomain);
      if (leaders[focusDomain].length > 1) {
        name = pack.questions[picked[0].q].scene + '에서 고른 두 답';
        line = picked.map(e => e.text).join(' / ');
      } else {
        name = pack.domains[focusDomain].labels[anchor[focusDomain]] + ' 한 컷';
        line = picked[0].text;
      }
    }
    const id = packId + '-' + leaders.map(indices => indices.length ? indices.join('') : 'x').join('-');
    return { counts, leaders, digest, name, line, evidence, id, characterIndex, kind, focusDomain };
  }

