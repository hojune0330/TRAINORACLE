  const context = await browser.newContext({ viewport: { width: 320, height: 812 }, reducedMotion: 'reduce', serviceWorkers: 'block' })
  await context.route('**/*', route => route.request().url().startsWith(origin + '/') ? route.continue() : route.abort())
