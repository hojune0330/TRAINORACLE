import assert from 'node:assert/strict'
import { mkdir } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { chromium } from '@playwright/test'

const base = process.env.GOAL_PROGRAM_LOCAL_URL ?? 'http://127.0.0.1:4176'
assert.ok(['127.0.0.1', 'localhost'].includes(new URL(base).hostname), 'Local synthetic checks only')
const output = new URL('../.codex-calendar-visual-qa/goal-youth-20261011/', import.meta.url)
await mkdir(output, { recursive: true })
const browser = await chromium.launch({ headless: true })
try {
  const context = await browser.newContext({ viewport: { width: 375, height: 812 }, serviceWorkers: 'block', reducedMotion: 'reduce' })
  await context.route('**/*', route => new URL(route.request().url()).origin === new URL(base).origin
    ? route.continue() : route.abort())
  const page = await context.newPage()
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  page.setDefaultTimeout(30_000)
  await page.goto(`${base}/?app=1&uitest=1`, { waitUntil: 'domcontentloaded', timeout: 60_000 })
  await page.getByRole('button', { name: '훈련 계획 만들기', exact: true }).click()
  await page.getByRole('button', { name: '10km 한 달 훈련표', exact: true }).click()
  await page.getByRole('heading', { name: '10km, 몇 분을 목표로 할까요?', exact: true }).waitFor({ state: 'visible' })
  assert.equal(await page.getByRole('heading', { name: '10km, 몇 분을 목표로 할까요?', exact: true }).isVisible(), true)
  assert.equal(await page.getByText('1km에 4분 30초', { exact: true }).isVisible(), true)
  await page.screenshot({ path: fileURLToPath(new URL('goal-step-1.png', output)), fullPage: true })
  await page.getByRole('button', { name: '45분 목표', exact: true }).click()
  await page.getByRole('heading', { name: '언제 시작할까요?', exact: true }).waitFor({ state: 'visible' })
  assert.equal(await page.getByRole('heading', { name: '언제 시작할까요?', exact: true }).isVisible(), true)
  await page.screenshot({ path: fileURLToPath(new URL('goal-step-2.png', output)), fullPage: true })
  await page.getByRole('button', { name: '다음', exact: true }).click()
  await page.getByRole('heading', { name: '달리기 경험은 어느 정도인가요?', exact: true }).waitFor({ state: 'visible' })
  assert.equal(await page.getByRole('heading', { name: '달리기 경험은 어느 정도인가요?', exact: true }).isVisible(), true)
  await page.screenshot({ path: fileURLToPath(new URL('goal-step-3.png', output)), fullPage: true })
  await page.getByRole('button', { name: '훈련 계획에 맞춰 달려 본 경험이 있어요', exact: true }).click()
  await page.getByRole('heading', { name: '어떤 방식으로 훈련할까요?', exact: true }).waitFor({ state: 'visible' })
  assert.equal(await page.getByRole('heading', { name: '어떤 방식으로 훈련할까요?', exact: true }).isVisible(), true)
  await page.screenshot({ path: fileURLToPath(new URL('goal-step-4.png', output)), fullPage: true })
  await page.getByRole('button', { name: /목표 속도로 연습/ }).click()
  await page.getByRole('heading', { name: '10km 45분 목표', exact: true }).waitFor()
  assert.equal(await page.evaluate(() => localStorage.getItem('trainoracle.goal-training-program.v1')), null)
  assert.equal(await page.getByRole('list', { name: '날짜별 계획 미리보기', exact: true }).locator(':scope > li').count(), 29)
  for (const width of [320, 375, 1280]) {
    await page.setViewportSize({ width, height: 900 })
    await page.getByRole('button', { name: '목록', exact: true }).click()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `List overflow at ${width}`)
    await page.screenshot({ path: fileURLToPath(new URL(`program-list-${width}.png`, output)), fullPage: true })
    await page.getByRole('button', { name: '달력', exact: true }).click()
    await page.getByRole('region', { name: '한 달 훈련표 · 9.5일 × 3', exact: true }).scrollIntoViewIfNeeded()
    assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), `Calendar overflow at ${width}`)
    await page.screenshot({ path: fileURLToPath(new URL(`program-calendar-${width}.png`, output)), fullPage: true })
  }
  await page.setViewportSize({ width: 375, height: 812 })
  const workoutDate = page.getByRole('grid').getByRole('button', { name: /주요 훈련/u }).first()
  await workoutDate.click()
  const reader = page.getByRole('dialog')
  await reader.waitFor({ state: 'visible' })
  const instructions = await reader.innerText()
  assert.match(instructions, /7분/u, 'Day reader must retain the prescribed work duration')
  assert.match(instructions, /60초|1분/u, 'Day reader must retain recovery duration')
  assert.match(instructions, /7분씩 3번/u, 'Day reader must explain repeats in reading order')
  assert.match(instructions, /1km에 4분 30초/u, 'Day reader must explain the same numeric target in minutes')
  assert.match(instructions, /52분 20초/u, 'Day reader must retain the complete workout duration')
  assert.match(instructions, /목표 속도 연습 \(RP\)/u, 'Day reader must preserve the training abbreviation')
  assert.match(instructions, /힘든 정도\(RPE\)/u, 'Effort guidance must keep its standard abbreviation')
  assert.doesNotMatch(instructions, /270초\/km|7min/u, 'Day reader must not require technical unit conversion')
  await page.screenshot({ path: fileURLToPath(new URL('program-day-reader-375.png', output)), fullPage: true })
  await reader.getByText('기존 훈련 표기', { exact: true }).click()
  assert.match(await reader.innerText(), /3 × 7min/u, 'Original concise notation must remain available')
  await page.screenshot({ path: fileURLToPath(new URL('program-original-notation-375.png', output)), fullPage: true })
  await reader.getByRole('button', { name: '달력으로 돌아가기', exact: true }).click()
  await reader.waitFor({ state: 'hidden' })
  assert.equal(await workoutDate.evaluate(element => document.activeElement === element), true)
  const durationCheck = page.getByRole('checkbox', { name: /^최대 .* 훈련시간을 확인했어요$/ })
  if (await durationCheck.count()) {
    assert.equal(await page.getByRole('button', { name: '이 계획 시작', exact: true }).isDisabled(), true)
    await durationCheck.check()
  }
  await page.getByRole('button', { name: '이 계획 시작', exact: true }).click()
  await page.getByRole('button', { name: '통증·몸 이상이 있거나 잘 모르겠어요', exact: true }).click()
  await page.getByRole('button', { name: '몸 상태 다시 확인', exact: true }).waitFor({ state: 'visible' })
  assert.equal(await page.getByRole('button', { name: '이 계획 시작', exact: true }).count(), 0)
  assert.equal(await page.evaluate(() => localStorage.getItem('trainoracle.goal-training-program.v1')), null)
  await page.getByRole('button', { name: '몸 상태 다시 확인', exact: true }).click()
  assert.equal(await page.getByRole('heading', { name: '지금 몸 상태는 어떤가요?', exact: true })
    .evaluate(element => document.activeElement === element), true)
  await page.getByRole('button', { name: '통증 없고 평소와 같아요 · 시작', exact: true }).click()
  await page.getByRole('button', { name: '이번 9.5일 보기·수정', exact: true }).waitFor()
  const saved = await page.evaluate(() => JSON.parse(localStorage.getItem('trainoracle.goal-training-program.v1')))
  assert.equal(saved.program.days.length, 29)
  assert.equal(saved.program.frames.length, 3)
  assert.equal(saved.application.currentCycleIndex, 1)
  assert.equal(saved.program.inputs.goalPaceConfirmed, true)
  await page.screenshot({ path: fileURLToPath(new URL('program-saved-375.png', output)), fullPage: true })
  await page.getByRole('button', { name: '이번 9.5일 보기·수정', exact: true }).click()
  await page.getByRole('button', { name: '10km 한 달 훈련표', exact: true }).click()
  await page.getByRole('button', { name: '이번 9.5일 보기·수정', exact: true }).waitFor()
  assert.equal(await page.getByRole('button', { name: '2차 훈련 시작', exact: true }).count(), 0)
  const reloaded = await page.evaluate(() => JSON.parse(localStorage.getItem('trainoracle.goal-training-program.v1')))
  assert.equal(reloaded.program.programId, saved.program.programId)
  await page.setViewportSize({ width: 320, height: 900 })
  await page.getByRole('button', { name: '목록', exact: true }).click()
  await page.evaluate(() => {
    const sizes = [...document.querySelectorAll('.goal-program *')].map(element => ({ element, size: parseFloat(getComputedStyle(element).fontSize) }))
    for (const { element, size } of sizes) element.style.fontSize = `${size * 2}px`
  })
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), 'Large-text overflow at 320')
  const activeAction = page.getByRole('button', { name: '이번 9.5일 보기·수정', exact: true })
  await activeAction.scrollIntoViewIfNeeded()
  assert.ok((await activeAction.boundingBox()).height >= 44)
  await page.screenshot({ path: fileURLToPath(new URL('program-large-text-320.png', output)), fullPage: true })
  assert.deepEqual(errors, [])
  console.log(JSON.stringify({ result: 'passed', widths: [320, 375, 1280], days: 29, cycles: 3,
    checks: ['four visible steps', 'plain per-km target and workout choice', 'no preview writes', 'date reader duration/recovery and return focus', 'body recheck focus without early save', 'local save/apply', 'existing active view round trip', 'next-cycle lock', 'no horizontal overflow', '200% synthetic text at 320', 'no page errors'] }))
  await context.close()
} finally { await browser.close() }
