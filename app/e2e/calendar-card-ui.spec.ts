import { expect, test } from "@playwright/test"

test("calendar overview stays compact, readable and reversible without losing training slots", async ({ page }, info) => {
  await page.clock.setFixedTime(new Date("2026-08-24T12:00:00+09:00"))
  await page.route("**/*", route => ["127.0.0.1", "localhost"].includes(new URL(route.request().url()).hostname) ? route.continue() : route.abort())
  await page.goto("/e2e/fixtures/calendar-ui.html")
  const grid = page.getByRole("grid")
  const selected = grid.locator('button[data-date="2026-08-30"]')
  await expect(selected).toContainText("훈련")
  await expect(grid).not.toContainText("PRIVATE_FIXTURE_MEMO")
  await expect(grid.locator(".calendar-training-mark")).toHaveCount(1)
  for (const width of [320, 375, 1280]) {
    await page.setViewportSize({ width, height: 800 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    for (const button of await grid.getByRole("button").all()) {
      const box = (await button.boundingBox())!
      expect(box.width).toBeGreaterThanOrEqual(44)
      expect(box.height).toBeGreaterThanOrEqual(44)
    }
    await page.screenshot({ path: info.outputPath(`journal-${width}.png`), fullPage: true })
  }
  await page.setViewportSize({ width: 375, height: 800 })
  await selected.click()
  await expect(page.getByRole("dialog")).toBeVisible()
  await page.getByRole("button", { name: /^(?:달력|하루씩)으로 돌아가기$/u, exact: true }).click()
  await expect(selected).toBeFocused()
  const trigger = page.getByRole("button", { name: /년월과 날짜 이동/ })
  await trigger.click()
  await page.getByLabel("날짜로 이동").focus()
  await page.keyboard.press("Escape")
  await expect(page.getByLabel("날짜로 이동")).toHaveCount(0)
  await expect(trigger).toBeFocused()
  await page.getByRole("button", { name: "화면 전환" }).click()
  await expect(selected).toContainText("오전")
  await expect(selected).toContainText("오후")
  await expect(selected.locator('[data-tone="main"]')).toHaveText("오전주요")
  await expect(selected.locator('[data-tone="recovery"]')).toHaveText("오후회복")
  await expect(selected.locator('[data-tone="main"] > svg')).toBeVisible()
  await page.getByText("훈련 색·종류 알아보기", { exact: true }).click()
  await expect(page.getByText("계획의 메인 운동", { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath("role-guide-375.png"), fullPage: true })
  await page.getByText("훈련 색·종류 알아보기", { exact: true }).click()
  await expect(grid.locator('[aria-current="date"]')).not.toHaveAttribute("data-selected")
  await page.setViewportSize({ width: 320, height: 800 })
  await page.screenshot({ path: info.outputPath("training-320.png"), fullPage: true })
  await page.getByRole("button", { name: /년월과 날짜 이동/ }).click()
  await page.screenshot({ path: info.outputPath("date-input-320.png"), fullPage: true })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.getByLabel("년월 선택").fill("2028-02")
  await page.getByLabel("날짜로 이동").fill("2028-02-29")
  await expect(page.locator('button[data-date="2028-02-29"]')).toHaveAttribute("data-selected", "true")
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.locator('.month-calendar button, .month-calendar th, .month-calendar__number').evaluateAll(elements => {
    const sizes = elements.map(el => parseFloat(getComputedStyle(el).fontSize))
    elements.forEach((el, index) => { (el as HTMLElement).style.fontSize = `${sizes[index]! * 2}px` })
  })
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath("large-text-320.png"), fullPage: true })
  await page.getByRole("button", { name: "처방 달력 확인" }).click()
  await page.getByRole("radio", { name: "달력", exact: true }).click()
  for (const width of [320, 375, 1280]) {
    await page.setViewportSize({ width, height: 800 })
    const main = page.locator('button[data-date="2026-08-24"] [data-tone="main"] .calendar-training-mark__label')
    await expect(main).toBeVisible()
    expect(await main.innerText()).toMatch(/^주요/)
    await expect(page.locator('button[data-date="2026-08-25"] [data-tone="off"]')).toContainText("오후")
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await page.screenshot({ path: info.outputPath(`prescription-${width}.png`), fullPage: true })
  }
})
