  await page.getByRole("navigation", { name: "주 탭" }).getByRole("button", { name: "홈", exact: true }).click()
  await page.getByRole("button", { name: /2026년 10월 6일 기록 1개 보기/ }).click()
  await page.getByText("계획한 훈련과 비교하기", { exact: true }).click()
  await expect(page.getByRole("heading", { name: "당시 계획한 훈련 방법" })).toBeVisible()
  if (outcome === "PARTIAL") await expect(page.getByText("내가 남긴 변경: 횟수를 줄였어요", { exact: true })).toBeVisible()
  await page.screenshot({ path: info.outputPath("original-journal.png"), fullPage: true, animations: "disabled" })
  await page.clock.setFixedTime(new Date("2026-10-11T03:00:00Z"))
