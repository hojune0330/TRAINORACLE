  await expect(page.getByRole("heading", { name: "9일 훈련 계획", exact: true })).toBeVisible()
  const successor = await storedPlan(page)
  expect(successor.intake.startDate).toBe("2026-10-11")
  expect(successor.activePlan.candidateId).not.toBe(changed.activePlan.candidateId)
