import { expect, test } from "@playwright/test"

test.use({ serviceWorkers: "block" })

for (const width of [320, 375, 1440]) {
  test(`Oracle keeps clear actions and return navigation at ${width}px`, async ({ page }, testInfo) => {
    await page.setViewportSize({ width, height: width === 1440 ? 900 : 740 })
    await page.goto("/?app=1")
    const tabs = page.getByRole("navigation", { name: "주 탭" })
    await expect(tabs.getByRole("button", { name: "훈련", exact: true })).toBeVisible()
    const oracle = tabs.getByRole("button", { name: "오라클", exact: true })
    await oracle.click()
    await expect(page.getByRole("heading", { name: "오라클", exact: true })).toBeVisible()
    const oracleMenu = page.getByRole("navigation", { name: "오라클 메뉴", exact: true })
    const analysis = oracleMenu.getByRole("button", { name: "분석", exact: true })
    await expect(analysis).toHaveAttribute("aria-current", "page")
    await expect(tabs).toHaveCount(0)
    await expect(page.locator(".app-tab-bar")).toHaveCount(1)
    await expect(page.getByRole("button", { name: "운동 기록 쓰기" })).toBeVisible()
    await expect(page.locator("html")).toHaveJSProperty("scrollWidth", width)
    await page.screenshot({ path: testInfo.outputPath(`oracle-${width}.png`) })

    const examplePreview = page.getByRole("region", { name: "기간별 훈련 리포트" })
    await expect(examplePreview.getByRole("heading", { name: "아직 이 기간에 남긴 기록이 없어요", exact: true })).toBeVisible()
    const openExample = examplePreview.getByRole("button", { name: "예시 결과 보기", exact: true })
    await openExample.click()
    await expect(examplePreview).toHaveAttribute("data-source", "example")
    await expect(page.getByRole("button", { name: "예시", exact: true })).toHaveAttribute("aria-pressed", "true")
    await expect(examplePreview.getByRole("img", { name: /예시 · 가상 기록.*월별 누적 거리/u })).toBeVisible()
    await expect(examplePreview.getByText("예시 · 가상 기록", { exact: true })).toBeVisible()
    await expect(page.locator("html")).toHaveJSProperty("scrollWidth", width)
    await page.screenshot({ path: testInfo.outputPath(`oracle-example-${width}.png`) })
    await examplePreview.getByRole("button", { name: "내 기록으로 보기", exact: true }).click()
    await expect(page.getByRole("heading", { name: "오라클", exact: true })).toBeVisible()
    await expect(analysis).toHaveAttribute("aria-current", "page")
    await expect(page.getByRole("combobox", { name: "살펴볼 주제" })).toHaveCount(0)
    await expect(page.getByRole("group", { name: "훈련 분석 자세히 보기" })
      .getByRole("button", { name: "훈련 요약", exact: true })).toHaveAttribute("aria-pressed", "true")
    await expect(examplePreview).toHaveAttribute("data-source", "my")
    await expect(examplePreview.getByRole("heading", { name: "아직 이 기간에 남긴 기록이 없어요", exact: true })).toBeVisible()
    await expect(tabs).toHaveCount(0)
    await expect(page.locator(".app-tab-bar")).toHaveCount(1)
  })
}
