import { expect, test, type Page, type TestInfo } from "@playwright/test"
import { completeQuickPlan } from "./plan-flow"

test.use({ serviceWorkers: "block" })

async function captureLayouts(page: Page, info: TestInfo, screen: string) {
  for (const width of [375, 320, 1280]) {
    await page.setViewportSize({ width, height: 800 })
    await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
    await expect.poll(() => page.locator(".app-scroll-region").evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
    await page.locator(".app-scroll-region").evaluate(el => { el.scrollTop = 0 })
    for (const card of await page.locator("button.category-card:visible, .category-disclosure > summary:visible").all()) {
      const bounds = await card.boundingBox()
      expect(bounds!.height).toBeGreaterThanOrEqual(44)
      expect(bounds!.x).toBeGreaterThanOrEqual(0)
      expect(bounds!.x + bounds!.width).toBeLessThanOrEqual(width + 1)
    }
    await page.screenshot({ path: info.outputPath(`${screen}-${width}.png`), fullPage: true })
  }
  await page.setViewportSize({ width: 375, height: 800 })
  await page.locator(".app-scroll-region").evaluate(el => { el.scrollTop = el.scrollHeight })
  await page.screenshot({ path: info.outputPath(`${screen}-lower-375.png`) })
  await page.locator(".app-scroll-region").evaluate(el => { el.scrollTop = 0 })
}

test("category cards open full workouts and visible editing without changing the plan", async ({ page }, info) => {
  test.setTimeout(120_000)
  page.setDefaultTimeout(20_000)
  await page.route("**/*", route => {
    const host = new URL(route.request().url()).hostname
    return host === "127.0.0.1" || host === "localhost" ? route.continue() : route.abort()
  })
  await page.clock.setFixedTime(new Date(2026, 9, 14, 12))
  await page.goto("/?app=1&uitest=1")
  await expect(page.locator(".app-scroll-region .app-loading-state")).toHaveCount(0)
  await page.getByRole("button", { name: "훈련 계획 만들기", exact: true }).click()
  await completeQuickPlan(page, { days: /^매일/u })
  await page.getByRole("button", { name: "이 일정으로 시작" }).click()
  await expect(page.getByRole("heading", { name: "9일 훈련 계획", exact: true })).toBeVisible()
  const before = await page.evaluate(() => localStorage.getItem("trainoracle.plan-beta.v1"))
  await page.getByRole("radiogroup", { name: "계획 일정 보기", exact: true }).getByRole("radio", { name: "달력", exact: true }).click()
  const today = page.locator(".instant-plan--entry-cards")
  const card = today.getByRole("button", { name: /훈련 내용 보기/ }).first()
  await expect(card).toContainText(/총 \d+분/u)
  await expect(card).not.toContainText("훈련 내용 보기")
  await expect(card).toHaveAttribute("data-category", "training")
  const pace = page.getByRole("button", { name: "페이스·훈련 구성", exact: true })
  await expect(pace).toHaveAttribute("aria-expanded", "false")
  const nextPlan = page.getByRole("button", { name: "다음 계획 준비", exact: true })
  await expect(nextPlan).toHaveAttribute("aria-expanded", "false")
  await captureLayouts(page, info, "training")
  await nextPlan.click()
  await expect(page.getByRole("button", { name: "현재 계획을 먼저 기록해 주세요", exact: true })).toBeDisabled()
  await nextPlan.click()
  await expect(page.getByRole("button", { name: "10km 한 달 훈련표", exact: true })).toBeVisible()
  await expect(page.getByRole("button", { name: "개인 계획 파일 불러오기", exact: true })).toBeVisible()

  await card.click()
  const reader = page.locator("dialog.plan-day-reader")
  await expect(reader).toBeVisible()
  await expect(reader.getByRole("term").filter({ hasText: /^본운동$/u })).toBeVisible()
  await expect(reader).toContainText(/\d+분/u)
  await reader.getByRole("button", { name: /^(?:달력|하루씩)으로 돌아가기$/u, exact: true }).click()
  await expect(reader).not.toBeVisible()
  await expect(card).toBeFocused()

  const edit = page.getByRole("button", { name: "계획 수정", exact: true })
  await edit.click()
  const editor = page.getByRole("region", { name: "계획 수정", exact: true })
  await expect(editor).toBeVisible()
  await expect(editor.getByRole("button", { name: /훈련 날짜 바꾸기/u })).toBeVisible()
  await expect(pace).toHaveAttribute("aria-expanded", "false")
  await editor.getByRole("button", { name: "계획 수정 닫기", exact: true }).click()
  await expect(edit).toBeFocused()
  await pace.focus()
  await page.keyboard.press("Enter")
  await expect(pace).toHaveAttribute("aria-expanded", "true")
  await expect(page.getByRole("button", { name: "기준 기록·페이스 바꾸기", exact: true })).toBeVisible()
  await pace.click()

  const tabs = page.getByRole("navigation", { name: "주 탭" })
  await tabs.getByRole("button", { name: "홈", exact: true }).click()
  const homeWorkout = page.getByRole("button", { name: /^\d{4}-\d{2}-\d{2} 오전 훈련 상세$/u }).first()
  await expect(homeWorkout).toBeVisible()
  const conditionDisclosure = page.getByText("컨디션 추가", { exact: true })
  await expect(conditionDisclosure).toBeVisible()
  await captureLayouts(page, info, "home")
  await homeWorkout.click()
  await expect(reader).toBeVisible()
  await expect(reader.getByRole("term").filter({ hasText: /^본운동$/u })).toBeVisible()
  await reader.getByRole("button", { name: /^(?:달력|하루씩)으로 돌아가기$/u, exact: true }).click()
  expect(await page.evaluate(() => localStorage.getItem("trainoracle.plan-beta.v1"))).toBe(before)

  await tabs.getByRole("button", { name: "일지", exact: true }).click()
  const journalMenu = page.getByRole("navigation", { name: "일지 메뉴", exact: true })
  const journalChoice = journalMenu.getByRole("button", { name: "일지", exact: true })
  await expect(journalChoice).toHaveAttribute("data-category", "journal")
  await expect(journalChoice).toBeVisible()
  await expect(page.locator(".app-scroll-region .app-loading-state")).toHaveCount(0)
  await captureLayouts(page, info, "journal")
  await journalMenu.getByRole("button", { name: "일지 나가기", exact: true }).click()
  // The Home workout link's return context is the same plan day reader.
  await expect(tabs.getByRole("button", { name: "훈련", exact: true })).toHaveAttribute("aria-current", "page")
  await expect(reader).toBeVisible()
  await expect(reader.getByRole("term").filter({ hasText: /^본운동$/u })).toBeVisible()
  await reader.getByRole("button", { name: /^(?:달력|하루씩)으로 돌아가기$/u, exact: true }).click()
  await expect(reader).not.toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem("trainoracle.plan-beta.v1"))).toBe(before)
  await tabs.getByRole("button", { name: "오라클", exact: true }).click()
  const oracleMenu = page.getByRole("navigation", { name: "오라클 메뉴", exact: true })
  const myTraining = oracleMenu.getByRole("button", { name: "분석", exact: true })
  await expect(myTraining).toHaveAttribute("aria-current", "page")
  await expect(myTraining).toHaveAttribute("data-category", "oracle")
  await expect(myTraining).toHaveCSS("background-color", "rgb(242, 238, 255)")
  await expect(page.locator(".app-tab-bar")).toHaveCount(1)
  await expect(tabs).toHaveCount(0)
  await captureLayouts(page, info, "oracle")
  await oracleMenu.getByRole("button", { name: "오라클 나가기", exact: true }).click()
  await expect(tabs.getByRole("button", { name: "훈련", exact: true })).toHaveAttribute("aria-current", "page")
  await expect(reader).toBeVisible()
  await expect(reader.getByRole("term").filter({ hasText: /^본운동$/u })).toBeVisible()
  await reader.getByRole("button", { name: /^(?:달력|하루씩)으로 돌아가기$/u, exact: true }).click()
  await expect(reader).not.toBeVisible()
  expect(await page.evaluate(() => localStorage.getItem("trainoracle.plan-beta.v1"))).toBe(before)
  for (const [name, category] of [["훈련", "training"], ["일지", "journal"], ["오라클", "oracle"]] as const) {
    await expect(tabs.getByRole("button", { name, exact: true })).toHaveAttribute("data-category", category)
  }
  await tabs.getByRole("button", { name: "오라클", exact: true }).click()
  await page.setViewportSize({ width: 320, height: 800 })
  await page.locator(".category-card__title, .category-card__description, button.category-choice, .app-navigation-dock span").evaluateAll(elements => {
    const sizes = elements.map(el => parseFloat(getComputedStyle(el).fontSize))
    elements.forEach((el, index) => (el as HTMLElement).style.setProperty("font-size", `${sizes[index]! * 2}px`, "important"))
  })
  expect(await page.locator(".app-scroll-region").evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  expect(await oracleMenu.evaluate(el => el.scrollWidth <= el.clientWidth)).toBe(true)
  await page.locator(".app-scroll-region").evaluate(el => { el.scrollTop = 0 })
  await page.screenshot({ path: info.outputPath("oracle-large-text-320.png") })
})
