  await gameCard(page, '장애물 생존').click()
  await expect(page.getByRole('radio', { name: /친구와 하기/ })).toBeChecked()
  await expect(page.getByText(/두 명이 각자 겨루는 개인전/)).toBeVisible()
  await page.getByRole('radio', { name: /혼자 하기/ }).check()
  await page.screenshot({ path: info.outputPath('game-detail.png') })
  await page.getByRole('button', { name: '게임 목록으로', exact: true }).click()
  await expect(gameCard(page, '장애물 생존')).toBeFocused()
  await expect(page.getByRole('button', { name: '친구와', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await page.getByRole('searchbox', { name: '게임 검색' }).fill('디펜스')
