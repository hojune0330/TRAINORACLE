import { expect, test, type Page } from "@playwright/test"

test.use({ serviceWorkers: "block" })

async function openGuestProfile(page: Page) {
  await page.getByRole("button", { name: "더보기", exact: true }).click()
  await page.getByRole("button", { name: "러닝 취향", exact: true }).click()
  await expect(page.locator(".oracle-v2__status").first()).toContainText("게스트")
}

async function answerAxis(page: Page, axis: string, answer: string) {
  const dialog = page.getByRole("dialog", { name: axis })
  for (let question = 1; question <= 3; question++) {
    await expect(dialog.getByText(`${question} / 3`, { exact: true })).toBeVisible()
    // Rapid clicks at the same point are guarded across questions; choose each answer deliberately.
    const answerButton = dialog.getByRole("button", { name: answer, exact: true })
    await answerButton.focus()
    await answerButton.press("Enter")
  }
  await expect(dialog.getByRole("heading", { name: "내 답을 정리했어요" })).toBeVisible()
  await dialog.getByRole("button", { name: "내 결과 보기", exact: true }).click()
}

for (const width of [320, 375, 1440]) {
  test(`guest profile keeps answers within the open app and clears them on reload at ${width}px`, async ({ page }, info) => {
    const errors: string[] = []
    page.on("pageerror", error => errors.push(error.message))
    await page.setViewportSize({ width, height: width === 1440 ? 900 : 812 })
    await page.goto("/?app=1")
    await openGuestProfile(page)
    await page.getByRole("button", { name: "내 훈련 방식 알아보기 · 질문 3개" }).click()
    await answerAxis(page, "계획 선호", "매우 그래요")
    const scores = page.locator('.preference-radar__value[data-scored="true"]')
    await expect(scores).toHaveCount(1)
    await expect(scores.first()).toHaveText("100점")
    await expect(page.getByRole("button", { name: "이 결과 보관" })).toBeDisabled()
    await expect(page.locator("html")).toHaveJSProperty("scrollWidth", width)
    await page.screenshot({ path: info.outputPath(`guest-profile-${width}.png`) })

    await page.goBack()
    await expect(page.getByRole("heading", { name: "더보기", exact: true })).toBeVisible()
    await page.getByRole("button", { name: "러닝 취향", exact: true }).click()
    await expect(scores.first()).toHaveText("100점")

    await page.getByRole("button", { name: "다른 취향 알아보기" }).click()
    const settings = page.getByRole("dialog", { name: "다른 취향 알아보기" })
    await expect(settings.getByRole("group", { name: "추가 취향" })).toBeVisible()
    await settings.getByRole("button", { name: "기록 도전 선호" }).click()
    await answerAxis(page, "기록 도전 선호", "그런 편이에요")
    await expect(scores).toHaveCount(2)
    await expect(scores.nth(1)).toHaveText("75점")
    expect(await page.evaluate(() => JSON.stringify(history.state))).not.toMatch(/STRUCTURE_1|CHALLENGE_1|selectedCharacter|answers/u)

    await page.reload()
    await openGuestProfile(page)
    await expect(page.getByRole("button", { name: "내 훈련 방식 알아보기 · 질문 3개" })).toBeVisible()
    await expect(scores).toHaveCount(0)
    await expect(page.locator(".oracle-v2__status").first()).toContainText("새로고침하면 사라져요")
    expect(errors).toEqual([])
  })
}

test("guest profile retains an in-screen draft, keeps question focus, and fits doubled text", async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 812 })
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/?app=1")
  await openGuestProfile(page)
  await page.getByRole("button", { name: "내 훈련 방식 알아보기 · 질문 3개" }).click()
  const dialog = page.getByRole("dialog", { name: "계획 선호" })
  await expect(dialog.getByRole("heading", { name: "달리기 전에 할 내용을 정해두는 것이 좋아요." })).toBeFocused()
  await dialog.getByRole("button", { name: "매우 그래요" }).click()
  await dialog.getByRole("button", { name: "닫기" }).click()
  await page.getByRole("button", { name: "작성하던 답 이어가기" }).click()
  await expect(dialog.getByText("2 / 3", { exact: true })).toBeVisible()
  await dialog.getByRole("button", { name: "이전 질문" }).click()
  await expect(dialog.getByRole("button", { name: "매우 그래요" })).toHaveAttribute("aria-pressed", "true")
  await page.evaluate(() => {
    const sizes = Array.from(document.querySelectorAll<HTMLElement>(".oracle-v2 h1, .oracle-v2 h2, .oracle-v2 p, .oracle-v2 button, .oracle-v2 strong, .oracle-v2 span"))
      .map(element => ({ element, size: parseFloat(getComputedStyle(element).fontSize) }))
    for (const { element, size } of sizes) element.style.fontSize = `${size * 2}px`
  })
  await expect(page.locator("html")).toHaveJSProperty("scrollWidth", 320)
  const closeButton = dialog.getByRole("button", { name: "닫기", exact: true })
  await expect(closeButton).toBeInViewport()
  const closeBox = (await closeButton.boundingBox())!
  expect(closeBox.x + closeBox.width).toBeLessThanOrEqual(320)
  await page.screenshot({ path: info.outputPath("guest-profile-draft-text-200.png") })
  await page.reload()
  await openGuestProfile(page)
  await expect(page.getByRole("button", { name: "내 훈련 방식 알아보기 · 질문 3개" })).toBeVisible()
  await expect(page.getByRole("button", { name: "작성하던 답 이어가기" })).toHaveCount(0)
})

test("preference questions and response management keep distinct destinations and modal return focus", async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 812 })
  await page.emulateMedia({ reducedMotion: "reduce" })
  await page.goto("/?app=1")
  await openGuestProfile(page)
  const interestsEntry = page.getByRole("button", { name: "다른 취향 알아보기", exact: true })
  await interestsEntry.click()
  const interests = page.getByRole("dialog", { name: "다른 취향 알아보기" })
  await expect(interests.getByRole("group", { name: "추가 취향" })).toBeVisible()
  await expect(interests.getByRole("button", { name: "응답 삭제" })).toHaveCount(0)
  await page.screenshot({ path: info.outputPath("other-preferences-320.png") })
  await interests.getByRole("button", { name: "계획 선호", exact: true }).click()
  const questions = page.getByRole("dialog", { name: "계획 선호" })
  const labels = ["아직 모르겠어요", "상황마다 달라요", "경험이 없어요"]
  for (const [index, label] of labels.entries()) {
    await expect(questions.getByRole("heading")).toBeFocused()
    const disclosure = questions.getByRole("button", { name: "고르기 어렵다면", exact: true })
    await expect(disclosure).toHaveAttribute("aria-expanded", "false")
    await expect(questions.locator('button[aria-pressed="true"]')).toHaveCount(0)
    await disclosure.click()
    if (index === 0) await page.screenshot({ path: info.outputPath("uncertain-responses-320.png") })
    const answer = questions.getByRole("button", { name: label, exact: true })
    await answer.focus()
    await answer.press("Enter")
  }
  await expect(questions.getByText("점수 없이 답만 정리했어요.")).toBeVisible()
  await questions.getByRole("button", { name: "내 결과 보기", exact: true }).click()
  await expect(interestsEntry).toBeFocused()
  const managerEntry = page.getByRole("button", { name: "내 응답·정보", exact: true })
  for (const width of [320, 375, 430, 1440]) {
    await page.setViewportSize({ width, height: 812 })
    await managerEntry.click()
    const manager = page.getByRole("dialog", { name: "내 응답·정보" })
    await expect(manager.getByRole("group", { name: "내 응답 확인·수정" })).toBeVisible()
    await expect(manager.getByRole("group", { name: "추가 취향" })).toHaveCount(0)
    await expect(manager.getByRole("button", { name: "읽을거리 살펴보기" })).toHaveCount(0)
    expect(await page.locator("html").evaluate(element => element.scrollWidth <= innerWidth)).toBe(true)
    const buttonSizes = await manager.getByRole("button").evaluateAll(buttons => buttons.map(button => {
      const box = button.getBoundingClientRect()
      return { width: box.width, height: box.height }
    }))
    expect(buttonSizes.every(box => box.width >= 44 && box.height >= 44)).toBe(true)
    await page.screenshot({ path: info.outputPath(`response-management-${width}.png`) })
    await manager.getByRole("button", { name: "응답 삭제", exact: true }).click()
    await expect(manager.getByRole("button", { name: "삭제하기", exact: true })).toBeVisible()
    await manager.getByRole("button", { name: "닫기", exact: true }).click()
    await expect(managerEntry).toBeFocused()
  }
  await managerEntry.click()
  const manager = page.getByRole("dialog", { name: "내 응답·정보" })
  await expect(manager.getByRole("button", { name: "삭제하기", exact: true })).toHaveCount(0)
  await manager.getByRole("button", { name: "계획 선호", exact: true }).click()
  await expect(questions.getByRole("heading", { name: "내 답을 정리했어요", exact: true })).toBeVisible()
  await questions.getByRole("button", { name: "내 결과 보기", exact: true }).click()
  await expect(managerEntry).toBeFocused()
  await page.setViewportSize({ width: 320, height: 812 })
  await page.getByRole("navigation", { name: "오라클 메뉴" }).getByRole("button", { name: "읽을거리", exact: true }).click()
  await page.getByRole("radiogroup", { name: "읽을거리 주제" }).getByRole("radio", { name: "배우기", exact: true }).click()
  const topic = page.getByRole("button", { name: "한 문제로 배우기", exact: true })
  await topic.click()
  const reading = page.getByRole("dialog", { name: "읽을거리", exact: true })
  const quizEntry = reading.getByRole("button", { name: "문제 풀기", exact: true })
  await quizEntry.click()
  const learning = page.getByRole("dialog", { name: "오라클 배움", exact: true })
  await expect(learning.getByRole("button", { name: "답 확인", exact: true })).toBeDisabled()
  const answer = learning.getByRole("radio").first()
  await answer.check()
  expect(await answer.locator("..").evaluate(element => getComputedStyle(element).borderRadius)).toBe("16px")
  await learning.getByRole("button", { name: "답 확인", exact: true }).click()
  await expect(learning.getByRole("status")).not.toBeEmpty()
  await page.screenshot({ path: info.outputPath("learning-quiz-320.png") })
  await learning.getByRole("button", { name: "다음 학습 페이지", exact: true }).click()
  await expect(learning.getByRole("heading")).toBeFocused()
  await expect(learning.getByRole("radio", { checked: true })).toHaveCount(0)
  await learning.evaluate(dialog => {
    const sizes = Array.from(dialog.querySelectorAll<HTMLElement>("h2, p, button, span, legend"))
      .map(element => ({ element, size: parseFloat(getComputedStyle(element).fontSize) }))
    for (const { element, size } of sizes) element.style.fontSize = `${size * 2}px`
  })
  await expect(learning.getByRole("button", { name: "닫기", exact: true })).toBeInViewport()
  const closeBox = (await learning.getByRole("button", { name: "닫기", exact: true }).boundingBox())!
  expect(closeBox.x + closeBox.width).toBeLessThanOrEqual(320)
  expect(await page.locator("html").evaluate(element => element.scrollWidth <= innerWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath("learning-quiz-text-200.png") })
  await learning.getByRole("button", { name: "닫기", exact: true }).click()
  await expect(quizEntry).toBeFocused()
  await reading.getByRole("button", { name: "닫기", exact: true }).click()
  await expect(topic).toBeFocused()
  await expect(page.getByRole("radiogroup", { name: "읽을거리 주제" }).getByRole("radio", { name: "배우기", exact: true })).toHaveAttribute("aria-checked", "true")
})

test("manual friend comparison keeps the existing long form usable without account access", async ({ page }, info) => {
  await page.setViewportSize({ width: 320, height: 812 })
  await page.goto("/?app=1")
  await openGuestProfile(page)
  const entry = page.getByRole("button", { name: "친구와 비교", exact: true })
  await entry.click()
  const reader = page.getByRole("dialog", { name: "친구와 비교", exact: true })
  await expect(reader.getByRole("button", { name: "친구 초대로 응답 비교", exact: true })).toBeDisabled()
  await reader.getByRole("button", { name: "직접 입력해서 비교", exact: true }).click()
  const friends = reader.getByRole("region", { name: "오라클 친구 비교", exact: true })
  await expect(friends.getByRole("heading", { name: "친구와 비교", exact: true })).toBeVisible()
  await friends.getByRole("checkbox", { name: /명시적으로 허락했어요/ }).check()
  const fields = friends.getByRole("group", { name: "친구가 비교를 허락한 항목", exact: true })
  for (const field of await fields.getByRole("checkbox").all()) await field.check()
  for (const summary of await friends.locator("details > summary").all()) {
    if (!await summary.evaluate(element => element.parentElement?.hasAttribute("open"))) await summary.click()
  }
  await friends.getByRole("heading", { name: "친구와 비교", exact: true }).scrollIntoViewIfNeeded()
  await page.screenshot({ path: info.outputPath("friend-comparison-top-320.png") })
  await expect(friends.getByRole("combobox", { name: "친구 경기 종목", exact: true })).toBeVisible()
  await expect(friends.getByRole("combobox")).toHaveCount(27)
  const preview = friends.getByRole("button", { name: "공유 미리보기", exact: true })
  await preview.scrollIntoViewIfNeeded()
  await expect(preview).toBeInViewport()
  await expect(preview).toBeDisabled()
  expect(await friends.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath("friend-comparison-bottom-320.png") })
  await friends.evaluate(region => {
    const sizes = Array.from(region.querySelectorAll<HTMLElement>("h1, h2, p, button, label, legend, summary, input, select, span"))
      .map(element => ({ element, size: parseFloat(getComputedStyle(element).fontSize) }))
    for (const { element, size } of sizes) element.style.fontSize = `${size * 2}px`
  })
  await preview.scrollIntoViewIfNeeded()
  await expect(preview).toBeInViewport()
  expect(await friends.evaluate(element => element.scrollWidth <= element.clientWidth)).toBe(true)
  await page.screenshot({ path: info.outputPath("friend-comparison-text-200.png") })
  await reader.getByRole("button", { name: "닫기", exact: true }).click()
  await expect(entry).toBeFocused()
})
