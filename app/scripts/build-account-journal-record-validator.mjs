import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const app = fileURLToPath(new URL('../', import.meta.url))
const root = path.dirname(app.replace(/[\\/]$/, ''))
const output = path.join(root, 'supabase/functions/_shared/account-journal-record-validator.mjs')

export async function buildAccountJournalRecordValidator() {
  return build({
    absWorkingDir: root,
    stdin: {
      contents: 'export { validateAccountJournalRecord, validateAccountJournalRecordUpdate } from "./src/domain/account/account-journal-record-schema.ts"',
      resolveDir: app,
      sourcefile: 'account-journal-record-server-entry.ts',
      loader: 'ts',
    },
    tsconfig: 'app/tsconfig.json',
    bundle: true,
    write: false,
    platform: 'neutral',
    format: 'esm',
    target: 'es2022',
    // Zod probes navigator to choose its JIT path. This artifact is server-only;
    // constant-fold that browser probe without changing the shared app schema.
    define: { navigator: 'undefined' },
    minify: true,
    legalComments: 'none',
    metafile: true,
    banner: { js: '// Generated by app/scripts/build-account-journal-record-validator.mjs; do not edit.' },
  })
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await buildAccountJournalRecordValidator()
  const generated = result.outputFiles[0].text
  if (process.argv.includes('--check')) {
    if (await readFile(output, 'utf8') !== generated) throw new Error('Account journal validator is stale; regenerate it.')
  } else {
    await writeFile(output, generated)
  }
  const reachable = Object.keys(result.metafile.inputs).filter(name => !name.includes('node_modules/')).sort()
  console.log(JSON.stringify({ check: process.argv.includes('--check'), bytes: Buffer.byteLength(generated), sourceInputs: reachable }, null, 2))
}
