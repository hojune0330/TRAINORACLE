import { build } from 'esbuild'
import { readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import path from 'node:path'

const app = fileURLToPath(new URL('../', import.meta.url))
const root = path.dirname(app.replace(/[\\/]$/, ''))
const output = path.join(root, 'server/self-hosted-coaching/contracts.mjs')
export async function buildCoachingRecordEvidence() {
  return build({
    absWorkingDir: root,
    stdin: { contents: `export { prepareCoachingRecordEvidence, buildCoachingEvidenceFacts } from './src/domain/coaching-record-evidence.ts';
      export { parseProviderDataLineage, providerDataGrantSchema, evaluateProviderDataUse, deriveProviderDataLineage } from './src/domain/provider-data-rights.ts';
      export { buildFileObservation } from './src/domain/import/file-observation.ts';`,
      resolveDir: app, sourcefile: 'coaching-record-evidence-server-entry.ts', loader: 'ts' },
    tsconfig: 'app/tsconfig.json', bundle: true, write: false, platform: 'neutral', format: 'esm', target: 'es2022',
    define: { navigator: 'undefined' }, minify: true, legalComments: 'none', metafile: true,
    banner: { js: '// Generated by app/scripts/build-coaching-record-evidence.mjs; do not edit.' },
  })
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const result = await buildCoachingRecordEvidence()
  const generated = result.outputFiles[0].text
  if (process.argv.includes('--check')) {
    const normalize = value => value.replace(/\r\n/gu, '\n')
    if (normalize(await readFile(output, 'utf8')) !== normalize(generated)) throw new Error('Coaching evidence contract is stale; regenerate it.')
  } else await writeFile(output, generated)
  console.log(JSON.stringify({ check: process.argv.includes('--check'), bytes: Buffer.byteLength(generated),
    sourceInputs: Object.keys(result.metafile.inputs).filter(name => !name.includes('node_modules/')).sort() }))
}
