import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const output = new URL('../../supabase/functions/_shared/account-file-document-codec.mjs', import.meta.url);
const result = await build({ entryPoints: [fileURLToPath(new URL('../src/domain/account/account-file-document-codec.ts', import.meta.url))],
  bundle: true, write: false, format: 'esm', platform: 'neutral', target: 'es2022',
  banner: { js: '// Generated by app/scripts/build-account-file-document-codec.mjs; do not edit.' } });
const source = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')).replaceAll('\r\n', '\n') !== source.replaceAll('\r\n', '\n')) throw new Error('Account file codec is stale.');
} else await writeFile(output, source);
console.log(JSON.stringify({ check: process.argv.includes('--check'), bytes: Buffer.byteLength(source) }));
