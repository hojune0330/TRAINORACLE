import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
const app = fileURLToPath(new URL('../', import.meta.url));
const output = new URL('../../supabase/functions/_shared/oracle-profile-comparison-validator.mjs', import.meta.url);
const result = await build({ absWorkingDir: app,
  entryPoints: ['src/domain/account/oracle-profile-comparison-contract.ts'],
  bundle: true, write: false, platform: 'neutral', format: 'esm', target: 'es2022', minify: true, legalComments: 'none',
  banner: { js: '// Generated by app/scripts/build-oracle-profile-comparison-validator.mjs; do not edit.' },
});
const text = result.outputFiles[0].text;
if (process.argv.includes('--check')) {
  if ((await readFile(output, 'utf8')).replace(/\r\n/gu, '\n') !== text) throw new Error('Comparison validator is stale');
} else await writeFile(output, text);
console.log(JSON.stringify({ check: process.argv.includes('--check'), bytes: Buffer.byteLength(text) }));
