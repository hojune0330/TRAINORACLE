import { cleanup, fireEvent, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { SleepInnGame } from './SleepInnGame'
import { activeJourney, DEFAULT_CONTEXT, getChapter, getHintAction, isSolved, parseState, PIECE_NAMES, SOLUTION, storageKey } from './engine'
import { encodeInvitation } from './social'
import type { SleepInnGameProps } from './types'

const date = '2026-10-18'
const props = (): SleepInnGameProps => ({ journal: { date, status: 'missing' }, persistenceScope: 'test-owner', onBack: vi.fn(), onOpenJournal: vi.fn() })
function enterPuzzle() {
  fireEvent.click(screen.getByRole('button', { name: '이야기 건너뛰기' }))
  expect(screen.getByRole('heading', { name: '여관을 닫을 시간' })).toBeVisible()
  fireEvent.click(screen.getByRole('button', { name: '바로 쉬기' }))
  expect(screen.getByText('수면을 측정하지 않아요. 지금 바로 이어가도 돼요.')).toBeVisible()
  fireEvent.click(screen.getByRole('button', { name: '다시 왔어요' }))
  expect(screen.getByRole('heading', { name: '오늘, 세 손님이 왔어요' })).toBeVisible()
  fireEvent.click(screen.getByRole('button', { name: '자리 정해 주기' }))
}
function solve() {
  fireEvent.click(screen.getByRole('button', { name: 'A1 모루' }))
  fireEvent.click(screen.getByRole('button', { name: 'B1 도담' }))
  expect(screen.getByRole('button', { name: '이 배치로 준비' })).toBeDisabled()
  fireEvent.click(screen.getByRole('button', { name: 'A1 도담' }))
  fireEvent.click(screen.getByRole('button', { name: 'C1 루미' }))
}
function savedJourney() { return activeJourney(parseState(window.localStorage.getItem(storageKey('test-owner')!)!)!) }
function solveCurrentBoard() {
  for (let count = 0; count < 30; count++) {
    const journey = savedJourney()
    if (isSolved(journey.layout, journey)) return
    const action = getHintAction(journey.layout, journey)
    expect(action).not.toBeNull()
    if (action?.type === 'rotateLamp') fireEvent.click(screen.getByRole('button', { name: /가림등.*돌리기/ }))
    else if (action?.type === 'swap') {
      const chapter = getChapter(journey)
      fireEvent.click(screen.getByRole('button', { name: new RegExp(`^${chapter.cells[action.from]} ${PIECE_NAMES[journey.layout[action.from]!]}`) }))
      fireEvent.click(screen.getByRole('button', { name: new RegExp(`^${chapter.cells[action.to]} ${PIECE_NAMES[journey.layout[action.to]!]}`) }))
    }
  }
  throw new Error('The real UI failed to reach a solved board within 30 legal hint moves')
}
function openChapterPuzzle() {
  fireEvent.click(screen.getByRole('button', { name: '이야기 건너뛰기' }))
  fireEvent.click(screen.getByRole('button', { name: '바로 쉬기' }))
  fireEvent.click(screen.getByRole('button', { name: '다시 왔어요' }))
  fireEvent.click(screen.getByRole('button', { name: /자리 정해 주기|새 시설 살펴보기/ }))
}
beforeEach(() => { window.localStorage.clear(); window.history.replaceState({}, '', '/') })
afterEach(() => { cleanup(); vi.restoreAllMocks() })

describe('SleepInnGame first chapter', () => {
  it('lands an invitation on the friends screen without automatically visiting or changing the inn', () => {
    const invitation = encodeInvitation({ ...DEFAULT_CONTEXT, layout: [...SOLUTION] })!
    window.history.replaceState({}, '', `/?app=1&games=lounge#sleep-inn=${invitation}`)
    render(<SleepInnGame {...props()} />)
    expect(screen.getByRole('heading', { name: '엽서로 만나는 친구' })).toBeVisible()
    expect(screen.getByRole('textbox', { name: '받은 초대장 또는 답장' })).toHaveValue(`#sleep-inn=${invitation}`)
    expect(screen.queryByRole('button', { name: '친구 방 둘러보기' })).not.toBeInTheDocument()
    expect(window.localStorage.getItem(storageKey('test-owner')!)).toBeNull()
    fireEvent.click(screen.getByRole('button', { name: '초대장 미리보기' }))
    expect(screen.getByRole('button', { name: '친구 방 둘러보기' })).toBeVisible()
    expect(window.localStorage.getItem(storageKey('test-owner')!)).toBeNull()
  })
  it('plays an unsolved board, swaps pieces, saves one completed postcard, and keeps explicit return actions', () => {
    const input = props()
    const view = render(<SleepInnGame {...input} />)
    expect(screen.queryByText('1장 완성')).not.toBeInTheDocument()
    enterPuzzle()
    const board = screen.getByRole('group', { name: '여섯 칸 객실 배치' })
    expect(within(board).getAllByRole('button')).toHaveLength(6)
    expect(within(board).getByText('A1')).toBeVisible()
    expect(within(board).getByText('C2')).toBeVisible()
    expect(screen.getByRole('button', { name: '이 배치로 준비' })).toBeDisabled()
    solve()
    expect(screen.getByRole('button', { name: '이 배치로 준비' })).toBeEnabled()
    expect(screen.queryByText('1장 완성')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '이 배치로 준비' }))
    expect(screen.getByText('1장 완성')).toBeVisible()
    const key = storageKey(input.persistenceScope)!
    expect(parseState(window.localStorage.getItem(key)!)?.postcards).toHaveLength(1)
    view.rerender(<SleepInnGame {...input} journal={{ date, status: 'recorded', entryId: 'existing-journal-id', sleepH: 7.5, sleepQuality: 3 }} />)
    expect(screen.getByText('1장 완성')).toBeVisible()
    expect(parseState(window.localStorage.getItem(key)!)?.postcards).toHaveLength(1)
    expect(screen.getByText('7시간 30분 · 수면 질 보통')).toBeVisible()
    expect(window.localStorage.getItem(key)).not.toMatch(/existing-journal-id|sleepH|sleepQuality/)
    fireEvent.click(screen.getByRole('button', { name: '일지로 돌아가기' }))
    expect(input.onOpenJournal).toHaveBeenCalledTimes(1)
    fireEvent.click(screen.getByRole('button', { name: '돌아가기' }))
    expect(input.onBack).toHaveBeenCalledTimes(1)
  })
  it('supports keyboard focus, selection cancellation, undo and a truthful hint', async () => {
    const user = userEvent.setup()
    render(<SleepInnGame {...props()} />)
    enterPuzzle()
    const lamp = screen.getByRole('button', { name: 'A1 모루' })
    lamp.focus()
    await user.keyboard('{Enter}')
    expect(lamp).toHaveAttribute('aria-pressed', 'true')
    await user.keyboard('{Escape}')
    expect(lamp).toHaveAttribute('aria-pressed', 'false')
    await user.keyboard('{Enter}{ArrowRight}{Enter}')
    screen.getByRole('button', { name: 'A1 도담' }).focus()
    await user.keyboard('{Enter}{ArrowRight}{ArrowRight}{Enter}')
    expect(screen.getByRole('button', { name: '이 배치로 준비' })).toBeEnabled()
    fireEvent.click(screen.getByRole('button', { name: '되돌리기' }))
    expect(screen.getByRole('button', { name: '이 배치로 준비' })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: '힌트' }))
    expect(screen.getByText(/두 자리를 바꿔 보세요\./)).toBeVisible()
  })
  it('allows optional night actions but does not infer completion from closing or elapsed time', () => {
    const input = props()
    const view = render(<SleepInnGame {...input} />)
    fireEvent.click(screen.getByRole('button', { name: '이야기 건너뛰기' }))
    fireEvent.click(screen.getByRole('button', { name: '커튼 닫기' }))
    expect(screen.getByRole('button', { name: '커튼 닫기' })).toHaveAttribute('aria-pressed', 'true')
    fireEvent.click(screen.getByRole('button', { name: '바로 쉬기' }))
    view.rerender(<SleepInnGame {...input} journal={{ date: '2026-10-19', status: 'missing' }} />)
    expect(screen.getByRole('heading', { name: '잠시 쉬어 가요' })).toBeVisible()
    expect(screen.getByText('2026-10-19')).toBeVisible()
    cleanup()
    render(<SleepInnGame {...input} journal={{ date: '2026-10-19', status: 'missing' }} />)
    expect(screen.getByRole('heading', { name: '잠시 쉬어 가요' })).toBeVisible()
    expect(screen.queryByText('1장 완성')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '다시 왔어요' }))
    expect(screen.getByRole('heading', { name: '오늘, 세 손님이 왔어요' })).toBeVisible()
  })
  it('holds completion after failed storage and retries the same postcard once', () => {
    const input = props()
    render(<SleepInnGame {...input} />)
    enterPuzzle(); solve()
    const write = vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('quota') })
    fireEvent.click(screen.getByRole('button', { name: '이 배치로 준비' }))
    expect(screen.queryByText('1장 완성')).not.toBeInTheDocument()
    expect(screen.getByRole('alert')).toHaveTextContent('저장하지 못했어요')
    expect(screen.getByRole('button', { name: 'B1 모루' })).toBeVisible()
    write.mockRestore()
    fireEvent.click(screen.getByRole('button', { name: '다시 저장하기' }))
    expect(screen.getByText('1장 완성')).toBeVisible()
    expect(parseState(window.localStorage.getItem(storageKey(input.persistenceScope)!)!)?.postcards).toHaveLength(1)
  })
  it('preserves a corrupt record and isolates owner/date changes', () => {
    const input = props(); const key = storageKey(input.persistenceScope)!
    window.localStorage.setItem(key, '{broken')
    const view = render(<SleepInnGame {...input} />)
    expect(screen.getByRole('alert')).toHaveTextContent('기존 저장은 그대로')
    fireEvent.click(screen.getByRole('button', { name: '이야기 건너뛰기' }))
    expect(window.localStorage.getItem(key)).toBe('{broken')
    view.rerender(<SleepInnGame {...input} persistenceScope="different-owner" />)
    expect(screen.queryByRole('alert')).not.toBeInTheDocument()
    expect(screen.getByRole('button', { name: '이야기 건너뛰기' })).toBeVisible()
    expect(window.localStorage.getItem(key)).toBe('{broken')
  })
  it('starts a fresh unsolved journey while preserving and reopening its completed postcard', () => {
    render(<SleepInnGame {...props()} />)
    enterPuzzle(); solve()
    fireEvent.click(screen.getByRole('button', { name: '이 배치로 준비' }))
    fireEvent.click(screen.getByRole('button', { name: '새 여정 시작' }))
    fireEvent.click(screen.getByRole('button', { name: '보관하고 새로 시작' }))
    expect(screen.queryByText('1장 완성')).not.toBeInTheDocument()
    fireEvent.click(screen.getByRole('button', { name: '여관 엽서 보관함' }))
    fireEvent.click(screen.getByRole('button', { name: /1장 · 꺼진 여관에 불 하나/ }))
    expect(screen.getByRole('heading', { name: '1장의 엽서' })).toBeVisible()
    fireEvent.click(screen.getByRole('button', { name: '진행 중인 여관으로' }))
    expect(screen.getByRole('button', { name: '이야기 건너뛰기' })).toBeVisible()
    expect(screen.queryByRole('button', { name: '다음 이야기' })).not.toBeInTheDocument()
  })
  it('plays all five chapters through real rules, facility choices and the season ending', () => {
    render(<SleepInnGame {...props()} />)
    for (let chapter = 1; chapter <= 5; chapter++) {
      openChapterPuzzle()
      if (chapter === 4 || chapter === 5) {
        expect(screen.getByRole('button', { name: '이 시설로 방 꾸미기' })).toBeDisabled()
        fireEvent.click(screen.getByRole('button', { name: chapter === 4 ? /가림등.*한 칸/ : /긴 온돌자리.*가로 두 칸/ }))
        fireEvent.click(screen.getByRole('button', { name: '이 시설로 방 꾸미기' }))
      }
      const board = screen.getByRole('group', { name: chapter === 5 ? '여덟 칸 객실 배치' : '여섯 칸 객실 배치' })
      expect(within(board).getAllByRole('button')).toHaveLength(chapter === 5 ? 8 : 6)
      if (chapter === 3) {
        fireEvent.click(screen.getByRole('button', { name: 'B2 온돌돌 고정' }))
        expect(screen.getByText(/바닥에 고정되어 있어요/)).toBeVisible()
        expect(savedJourney().layout[4]).toBe('stone')
      }
      if (chapter === 4) {
        fireEvent.click(screen.getByRole('button', { name: /가림등.*돌리기/ }))
        expect(savedJourney().lampDirection).toBe('east')
        fireEvent.click(screen.getByRole('button', { name: '되돌리기' }))
        expect(savedJourney().lampDirection).toBe('north')
      }
      expect(screen.getByRole('button', { name: '이 배치로 준비' })).toBeDisabled()
      solveCurrentBoard()
      fireEvent.click(screen.getByRole('button', { name: '이 배치로 준비' }))
      expect(screen.getByText(`${chapter}장 완성`)).toBeVisible()
      expect(parseState(window.localStorage.getItem(storageKey('test-owner')!)!)?.postcards).toHaveLength(chapter)
      if (chapter < 5) fireEvent.click(screen.getByRole('button', { name: '다음 이야기' }))
    }
    expect(screen.getByText('다섯 장의 이야기를 모두 모았어요.')).toBeVisible()
    expect(screen.queryByRole('button', { name: '다음 이야기' })).not.toBeInTheDocument()
    expect(savedJourney().phase).toBe('seasonComplete')
  }, 30000)
  it('archives an unfinished room and resumes its exact board without replacing postcards', () => {
    render(<SleepInnGame {...props()} />)
    enterPuzzle()
    fireEvent.click(screen.getByRole('button', { name: 'A1 모루' }))
    fireEvent.click(screen.getByRole('button', { name: 'B1 도담' }))
    const before = savedJourney()
    fireEvent.click(screen.getByRole('button', { name: '보관함' }))
    fireEvent.click(screen.getByRole('button', { name: '새 여정 시작' }))
    fireEvent.click(screen.getByRole('button', { name: '보관하고 새로 시작' }))
    expect(savedJourney().id).not.toBe(before.id)
    fireEvent.click(screen.getByRole('button', { name: '보관함' }))
    fireEvent.click(screen.getByRole('button', { name: '이어하기' }))
    expect(savedJourney().id).toBe(before.id)
    expect(savedJourney().layout).toEqual(before.layout)
    expect(savedJourney().history).toEqual(before.history)
    expect(screen.getByRole('button', { name: 'A1 도담' })).toBeVisible()
  })
  it('keeps next chapter and a new journey closed when persistence fails', () => {
    render(<SleepInnGame {...props()} />)
    enterPuzzle(); solve()
    fireEvent.click(screen.getByRole('button', { name: '이 배치로 준비' }))
    const before = savedJourney()
    vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('quota') })
    fireEvent.click(screen.getByRole('button', { name: '다음 이야기' }))
    expect(screen.getByText('1장 완성')).toBeVisible()
    expect(savedJourney()).toEqual(before)
    fireEvent.click(screen.getByRole('button', { name: '새 여정 시작' }))
    fireEvent.click(screen.getByRole('button', { name: '보관하고 새로 시작' }))
    expect(screen.getByRole('group', { name: '새 여정 시작 확인' })).toBeVisible()
    expect(savedJourney()).toEqual(before)
  })
  it('guards a failed-save exit and closes only after retry succeeds or explicit discard', () => {
    const input = props()
    render(<SleepInnGame {...input} />)
    enterPuzzle()
    const write = vi.spyOn(Storage.prototype, 'setItem').mockImplementation(() => { throw new Error('quota') })
    fireEvent.click(screen.getByRole('button', { name: 'A1 모루' }))
    fireEvent.click(screen.getByRole('button', { name: 'B1 도담' }))
    fireEvent.click(screen.getByRole('button', { name: '돌아가기' }))
    expect(input.onBack).not.toHaveBeenCalled()
    expect(screen.getByRole('group', { name: '저장되지 않은 여관 나가기' })).toBeVisible()
    fireEvent.click(screen.getByRole('button', { name: '저장하고 돌아가기' }))
    expect(input.onBack).not.toHaveBeenCalled()
    write.mockRestore()
    fireEvent.click(screen.getByRole('button', { name: '저장하고 돌아가기' }))
    expect(input.onBack).toHaveBeenCalledOnce()
    expect(savedJourney().layout[0]).toBe('turtle')
  })
})
