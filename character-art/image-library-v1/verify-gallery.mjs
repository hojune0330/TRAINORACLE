import { createRequire } from 'node:module';
const { chromium } = createRequire(new URL('../../app/package.json', import.meta.url))('playwright');
import { pathToFileURL, fileURLToPath } from 'node:url';
import { resolve, dirname } from 'node:path';
import { mkdirSync, writeFileSync } from 'node:fs';
const root=dirname(fileURLToPath(import.meta.url));
const out=resolve(root,'review');mkdirSync(out,{recursive:true});
const url=process.argv[2]??pathToFileURL(resolve(root,'index.html')).href;
const browser=await chromium.launch({headless:true});
const page=await browser.newPage({viewport:{width:1200,height:900}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto(url);await page.waitForSelector('article');
await page.locator('img').evaluateAll(imgs=>imgs.forEach(img=>img.loading='eager'));
await page.waitForFunction(()=>Array.from(document.querySelectorAll('article img')).every(img=>img.complete&&img.naturalWidth>0));
if(await page.locator('article').count()!==30)throw Error('Expected 30 assets');
if(!(await page.locator('#summary').innerText()).includes('30 / 30'))throw Error('Not all produced');
const count={};
for(const [filter,expected] of [['defense',12],['world',10],['fx',8],['first',4]]){
 await page.locator('[data-filter="'+filter+'"]').click();
 count[filter]=await page.locator('article').count();if(count[filter]!==expected)throw Error('Filter '+filter);
 await page.locator('img').evaluateAll(imgs=>imgs.forEach(img=>img.loading='eager'));
 await page.waitForFunction(()=>Array.from(document.querySelectorAll('article img')).every(img=>img.complete&&img.naturalWidth>0));
 if(filter!=='first')await page.screenshot({path:resolve(out,filter+'-gallery.png'),fullPage:true});
}
await page.locator('[data-filter="all"]').click();
await page.locator('.preview').first().click();await page.waitForSelector('dialog[open]');
if((await page.locator('#viewer-image').getAttribute('src'))!=='defense/td-rapid-tower.png')throw Error('Dialog source');
await page.keyboard.press('Escape');if(await page.locator('dialog[open]').count())throw Error('Dialog close');
if(!await page.locator('.preview').first().evaluate(el=>el===document.activeElement))throw Error('Focus restoration');
await page.locator('#background').click();if(await page.locator('body').getAttribute('data-background')!=='dark')throw Error('Background toggle');
await page.setViewportSize({width:360,height:800});
await page.locator('[data-filter="defense"]').click();
await page.screenshot({path:resolve(out,'phone-dark.png'),fullPage:false});
const mobileOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
await page.setViewportSize({width:320,height:700});
const narrowOverflow=await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth);
if(mobileOverflow||narrowOverflow)throw Error('Mobile overflow');
await page.locator('#background').click();
await page.locator('.preview').first().click();
await page.screenshot({path:resolve(out,'phone-detail.png'),fullPage:false});
await page.locator('#close-viewer').click();
await page.setViewportSize({width:1440,height:1100});
await page.locator('[data-filter="all"]').click();
await page.locator('img').evaluateAll(imgs=>imgs.forEach(img=>img.loading='eager'));
await page.waitForFunction(()=>Array.from(document.querySelectorAll('article img')).every(img=>img.complete&&img.naturalWidth>0));
await page.addStyleTag({content:'.intro,.toolbar,.summary,footer,.role,.sizes,.stage,.meta,.actions{display:none!important}.grid{grid-template-columns:repeat(6,minmax(0,1fr));gap:12px}main{max-width:1440px;padding:12px}.preview{height:190px;aspect-ratio:auto;padding:8px}.preview img{max-height:174px}article{padding-bottom:8px}article h2{font-size:14px;margin:8px 0 0}'});
await page.screenshot({path:resolve(out,'all-30-contact.png'),fullPage:true});
const report={pass:!errors.length,url:url.startsWith('file:')?'local-gallery':url,planned:30,imagesLoaded:30,filterCounts:count,dialog:true,focusReturn:true,backgroundToggle:true,mobileOverflow,narrowOverflow,errors,scope:'Asset gallery browser and readability review. No gameplay integration or Tripo conversion.'};
writeFileSync(resolve(out,'browser-check.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report));await browser.close();
