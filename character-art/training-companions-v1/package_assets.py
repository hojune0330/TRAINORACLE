"""Pack local Blender renders; preserve the same framing across every motion frame."""
from pathlib import Path
from PIL import Image
import json, hashlib

root=Path(__file__).resolve().parents[2]
frames=root/'.scratch/companion-frames'
public=root/'app/public'
stickers=public/'collections/training-companions-v1'
motiondir=public/'companions/v1'
stickers.mkdir(parents=True,exist_ok=True); motiondir.mkdir(parents=True,exist_ok=True)
def bounds(images):
    boxes=[im.getchannel('A').point(lambda v:255 if v>8 else 0).getbbox() for im in images]
    boxes=[b for b in boxes if b]
    x0=min(b[0] for b in boxes);y0=min(b[1] for b in boxes)
    x1=max(b[2] for b in boxes);y1=max(b[3] for b in boxes)
    side=max(x1-x0,y1-y0)*1.12;cx=(x0+x1)/2;cy=(y0+y1)/2
    return (round(cx-side/2),round(cy-side/2),round(cx+side/2),round(cy+side/2))
def fit(im,box,size):return im.crop(box).resize((size,size),Image.Resampling.LANCZOS)
animals={'otter':'수달','cat':'고양이','bear':'곰'}
poses={'run':'달리는','walk':'걷는','warm_up':'몸 푸는'}
manifest=[]
for animal,name in animals.items():
    for pose,verb in poses.items():
        im=Image.open(frames/f'{animal}-{pose}.png').convert('RGBA')
        target=stickers/f'{animal}-{pose.replace("_", "-")}.webp'
        fit(im,bounds([im]),320).save(target,quality=88,method=6)
        manifest.append({'id':f'COMPANION_{animal.upper()}_{pose.upper()}','name':f'{verb} {name}',
          'description':f'내가 고른 {name}을 일지에 붙여요.','fileName':target.name,'group':animal.upper(),
          'licenseId':'TRAINORACLE_COMPANIONS_TRIPO','sourceAsset':f'trainoracle-{animal}-exercise-set-v3.glb#{pose}',
          'sha256':hashlib.sha256(target.read_bytes()).hexdigest()})
for motion in ['run','walk','warm_up','nod']:
    images=[Image.open(frames/f'otter-{motion}-{i:02}.png').convert('RGBA') for i in range(16)]
    box=bounds(images)
    atlas=Image.new('RGBA',(192*16,192))
    for i,im in enumerate(images):atlas.paste(fit(im,box,192),(192*i,0))
    atlas.save(motiondir/f'otter-{motion}-atlas.webp',quality=83,method=6)
    if motion=='nod':fit(images[0],box,320).save(motiondir/'otter-nod.webp',quality=88,method=6)
definition={
 'id':'TRAINING_COMPANIONS_V1','title':'운동하는 동물','subtitle':'9종 · 무료',
 'artDirection':'원본 수달·고양이·곰의 무광 3D 모델에서 만든 작은 운동 스티커.',
 'sourceNote':'TrainOracle 원본 이미지를 Tripo에서 3D로 만들고 직접 렌더링했어요.',
 'assetDir':'collections/training-companions-v1','render':{'width':320,'height':320,'transparentBackground':True},
 'groups':[{'id':a.upper(),'label':n} for a,n in animals.items()],
 'defaultAcquisition':{'kind':'POINTS','cost':0},'bundle':{'cost':0},'availability':'ACTIVE',
 'entryPreviewItemIds':['COMPANION_OTTER_RUN','COMPANION_CAT_WARM_UP','COMPANION_BEAR_WALK','COMPANION_OTTER_WALK'],
 'licenseReviewedOn':'2026-10-15','items':manifest,
}
target=root/'app/src/domain/training-companion-collection.ts'
target.write_text('import type { DecorationCollection } from "./decoration-collections"\n\n// Generated by character-art/training-companions-v1/package_assets.py.\nexport const TRAINING_COMPANIONS_V1 = '+json.dumps(definition,ensure_ascii=False,indent=2)+' as const satisfies DecorationCollection\n',encoding='utf8')
ledger=[{'file':str(p.relative_to(public)).replace('\\','/'),'bytes':p.stat().st_size,'sha256':hashlib.sha256(p.read_bytes()).hexdigest()} for folder in [stickers,motiondir] for p in sorted(folder.glob('*.webp'))]
(root/'character-art/training-companions-v1/runtime-assets.json').write_text(json.dumps(ledger,indent=2),encoding='utf8')
print(json.dumps({'files':len(ledger),'bytes':sum(i['bytes'] for i in ledger)},indent=2))
